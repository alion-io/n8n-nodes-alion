#!/usr/bin/env node
// Writes nodes/Alion/filters.generated.ts: the optional filters of each Alion tool the node covers, as n8n
// collection options, from the server's own tool schemas.
//
//   node scripts/generate.mjs            fetch https://alion.io/mcp/tools into schema/tools.json, then generate
//   node scripts/generate.mjs --offline  generate from the schema/tools.json snapshot
//
// The main field of each operation (the company, the job, the query) is written by hand in the node; everything
// else a tool accepts becomes a filter here, so a filter added on alion.io reaches the node by running this script.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SNAPSHOT = join(ROOT, 'schema', 'tools.json');

// the tools the node covers and the arguments it sets itself (main fields, paging, output size)
const TOOLS = {
	search_companies: ['query', 'sort', 'detail', 'limit', 'cursor'],
	similar_companies: ['company', 'detail', 'limit'],
	search_jobs: ['query', 'sort', 'detail', 'limit', 'cursor'],
	search_investors: ['query', 'sort', 'detail', 'limit', 'cursor'],
	market_stats: ['role', 'country'],
};

// n8n wants booleans described as "Whether ..."; the server's wording is for agents
const BOOLEAN_TEXT = {
	hiring: 'Whether to keep only companies with open roles now (off keeps only those with none)',
	startup: 'Whether to keep only companies Alion classifies as startups (off keeps everyone else)',
	include_agencies: 'Whether to include staffing and recruiting agencies, which are left out by default',
	visa_sponsorship: 'Whether to keep only postings that state visa sponsorship',
	visa_sponsor: "Whether to keep only employers in the official visa sponsor registers of the posting's country",
	visa_salary: "Whether to keep only postings whose stated yearly pay reaches the country's work-permit salary floor",
	has_equity: 'Whether to keep only postings that offer equity',
	portfolio_hiring: 'Whether to keep only investors whose portfolio companies hire now',
	has_exits: 'Whether to keep only investors with exits (portfolio companies listed or acquired)',
	open_to_pitches: 'Whether to keep only funds that say they take pitches',
};

const ACRONYMS = { usd: 'USD', ats: 'ATS', ai: 'AI', hq: 'HQ', id: 'ID', url: 'URL' };
const title = (s) => s.split('_').map((w) => ACRONYMS[w] || w[0].toUpperCase() + w.slice(1)).join(' ');
const OPTION_NAMES = { on_site: 'On-Site', full_time: 'Full-Time', part_time: 'Part-Time' };
const optionName = (v) => OPTION_NAMES[v] || (/^[A-Z]$/.test(v) ? v : title(String(v)));

// one sentence, no trailing period (n8n's style for parameter descriptions)
function describe(text) {
	const t = String(text || '').replace(/\s+/g, ' ').trim();
	return t.replace(/\.$/, '');
}

function field(name, s) {
	const types = Array.isArray(s.type) ? s.type.filter((x) => x !== 'null') : [s.type];
	const type = types[0];
	const base = { displayName: title(name), name };
	if (type === 'boolean') {
		if (!BOOLEAN_TEXT[name]) throw new Error(`boolean ${name}: add its "Whether ..." text to BOOLEAN_TEXT`);
		return { ...base, type: 'boolean', default: true, description: BOOLEAN_TEXT[name] };
	}
	if (s.enum) {
		const options = s.enum.map((v) => ({ name: optionName(v), value: v })).sort((a, b) => a.name.localeCompare(b.name));
		return { ...base, type: 'options', options, default: s.default ?? s.enum[0], description: describe(s.description) };
	}
	if (type === 'integer' || type === 'number') {
		const typeOptions = {};
		if (s.minimum !== undefined) typeOptions.minValue = s.minimum;
		if (s.maximum !== undefined) typeOptions.maxValue = s.maximum;
		const def = s.default ?? s.minimum ?? 0;
		return { ...base, type: 'number', ...(Object.keys(typeOptions).length ? { typeOptions } : {}), default: def, description: describe(s.description) };
	}
	return { ...base, type: 'string', default: '', description: describe(s.description) };
}

const data = JSON.parse(readFileSync(SNAPSHOT, 'utf8'));
if (!process.argv.includes('--offline')) {
	const res = await fetch('https://alion.io/mcp/tools', { headers: { Accept: 'application/json', 'User-Agent': 'n8n-nodes-alion-generator' } });
	if (!res.ok) throw new Error(`GET https://alion.io/mcp/tools -> HTTP ${res.status}`);
	Object.assign(data, await res.json());
	writeFileSync(SNAPSHOT, JSON.stringify(data, null, 2) + '\n');
}

let out = `// Generated by scripts/generate.mjs from https://alion.io/mcp/tools (server ${data.server?.name} ${data.server?.version}).\n// Do not edit by hand: run \`node scripts/generate.mjs\`.\n\nimport type { INodeProperties } from 'n8n-workflow';\n\n`;
for (const [tool, skip] of Object.entries(TOOLS)) {
	const t = data.tools.find((x) => x.name === tool);
	if (!t) throw new Error(`the server no longer lists ${tool}`);
	const props = t.inputSchema?.properties || {};
	const fields = Object.entries(props).filter(([k]) => !skip.includes(k)).map(([k, s]) => field(k, s));
	fields.sort((a, b) => a.displayName.localeCompare(b.displayName));
	out += `export const ${tool.replace(/_([a-z])/g, (_, c) => c.toUpperCase())}Filters: INodeProperties[] = ${JSON.stringify(fields, null, '\t')};\n\n`;
}
// the sort order of each search, as a static "Sort" collection (n8n's linter reads defaults statically)
for (const tool of Object.keys(TOOLS)) {
	const s = data.tools.find((x) => x.name === tool).inputSchema?.properties?.sort;
	if (!s?.enum) continue;
	const order = { displayName: 'Order', name: 'order', type: 'options', options: s.enum.map((v) => ({ name: optionName(v), value: v })).sort((x, y) => x.name.localeCompare(y.name)), default: s.default ?? s.enum[0], description: describe(s.description) };
	const prop = { displayName: 'Sort', name: 'sort', type: 'collection', placeholder: 'Add Sort', default: {}, options: [order] };
	out += `export const ${tool.replace(/_([a-z])/g, (_, c) => c.toUpperCase())}Sort: INodeProperties = ${JSON.stringify(prop, null, '	')};

`;
}
writeFileSync(join(ROOT, 'nodes', 'Alion', 'filters.generated.ts'), out);
console.log(`filters for ${Object.keys(TOOLS).length} tools from ${data.server?.name} ${data.server?.version}`);
